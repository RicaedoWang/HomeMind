"""租户（家庭）标识的公共常量。

为什么单独一个模块：
租户标识要被工具层、记忆层、API 层、Agent 层同时用到，
如果各模块各写一个字符串常量，迟早出现"这边叫 family_sz、那边写成 sz"的裂缝，
而租户裂缝就是数据泄露。放在这里，谁要用都从同一处 import。

这里只放常量与纯函数，不放任何 IO——保持零依赖，谁 import 都不会引入循环。
"""

from __future__ import annotations

# 默认家庭：单元测试、评测这类"没有登录态"的场景都落到这里。
# 生产路径（API / Agent 主链路）必须显式传入 family_id，
# 漏传就会读到别人家的数据——这条契约由 tests/test_tenant_isolation.py 守着。
DEFAULT_FAMILY_ID = "family_sz"

# 服务端注入的租户字段名。
# 为什么带双下划线前缀：它**不出现在工具 Schema 里**，模型看不见也造不出来。
# 让模型能指定租户 = 用户一句话"去把小明家的灯关了"就可能真的执行，
# 租户边界必须由服务端说了算，不能交给模型输出。
FAMILY_ARG = "__family_id"
